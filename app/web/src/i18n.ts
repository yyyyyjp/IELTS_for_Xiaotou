const messages: Record<Lang, Record<string, string>> = { zh, en }

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const lang = ref<Lang>(initialLang())

watch(
  lang,
  (value) => {
    document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en'
    try {
      localStorage.setItem(STORAGE_KEY, value)
    } catch {
      /* ignore */
    }
  },
  { immediate: true },
)

export function t(key: string, vars?: Record<string, string | number>): string {
  let text = messages[lang.value][key] ?? messages.zh[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function setLang(value: Lang): void {
  lang.value = value
}

export function toggleLang(): void {
  lang.value = lang.value === 'zh' ? 'en' : 'zh'
}

export function useI18n() {
  return { lang, t, setLang, toggleLang }
}

export const locale = () => (lang.value === 'zh' ? 'zh-CN' : 'en-GB')
